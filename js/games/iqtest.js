  /* ============================================================================
   *  SECTION 4 — FINISH: IQ SCORE + RADAR + RESULTS SCREEN
   *  ---------------------------------------------------------------------------
   *  Scoring mapping (documented):
   *    - Each Q base = difficulty * 10
   *    - speed multiplier ∈ [0.85 .. 1.5]
   *    - streak multiplier ∈ [1.0 .. 1.4]
   *    - Total raw points → normalized to 0..1 via best-possible ceiling
   *    - Standard IQ score: mean 100, SD 15
   *        iq = round(75 + norm * 60)  clamp [70,145]
   *        (a norm of 0.5 → IQ 105; norm 1.0 → IQ 135; strong bonuses can nudge
   *         above 135 via streak + speed but hard-capped at 145.)
   *    - Percentile from a normal(100,15) bell curve.
   *    - 5 skill scores (Pattern, Spatial, Logic, Memory, Speed) derived from
   *      per-question `skills[]`: each correct answer contributes to every skill
   *      listed on that question; final = correct_sum / weighted_max.
   * ============================================================================ */
  function computeScores(){
    /* max possible pts (if all correct with best speed & max streak) */
    let bestPossible = 0;
    IQ_QUESTIONS.forEach((q,i)=>{
      const base = q.difficulty * 10;
      const streakMult = 1 + Math.min(0.4, i * 0.08); /* actually streak grows through the run */
      bestPossible += base * 1.5 * Math.min(1.4, streakMult);
    });
    /* Simpler ceiling estimate: sum of (base * 1.5 * 1.4) */
    const cap = IQ_QUESTIONS.reduce((s,q)=> s + q.difficulty*10*1.5*1.4, 0);
    const norm = IQ_clamp(state.totalPts / cap, 0, 1);
    let iq = Math.round(75 + norm * 60);
    iq = IQ_clamp(iq, 70, 145);

    /* Skill scoring */
    const skillTotals = { pattern:0, spatial:0, logic:0, memory:0, speed:0 };
    const skillMax    = { pattern:0, spatial:0, logic:0, memory:0, speed:0 };
    /* "Speed" skill: fraction of the time remaining on correct answers */
    let speedNumer=0, speedDenom=0;
    state.results.forEach((r,idx)=>{
      const q = IQ_QUESTIONS[idx];
      if(!q) return;
      (q.skills||[]).forEach(s=>{
        if(skillMax[s] == null){ skillMax[s]=0; skillTotals[s]=0; }
        skillMax[s] += q.difficulty;
        if(r.correct) skillTotals[s] += q.difficulty;
      });
      /* Speed skill = avg (1 - timeRatio) on correct answers */
      if(r.correct){
        const ratio = r.elapsedMs / r.limitMs;
        speedNumer += (1 - IQ_clamp(ratio, 0, 1));
        speedDenom += 1;
      }
    });
    const skills = {};
    ['pattern','spatial','logic','memory'].forEach(s=>{
      skills[s] = skillMax[s] ? skillTotals[s]/skillMax[s] : 0;
    });
    skills.speed = speedDenom ? speedNumer/speedDenom : 0;

    /* Accuracy + timing stats */
    const total = state.results.length;
    const correct = state.results.filter(r=>r.correct).length;
    const avgMs = total ? state.results.reduce((s,r)=>s+r.elapsedMs,0)/total : 0;

    return { iq, norm, cap, skills, correct, total, avgMs, bestStreak:state.bestStreak };
  }

  function pickTips(scores){
    /* Personalized 2-3 tips based on the skill radar. */
    const tips=[];
    const sorted = Object.entries(scores.skills).sort((a,b)=>a[1]-b[1]);
    const weakest = sorted[0], secondWeak = sorted[1];
    const strongest = sorted[sorted.length-1];

    const advice = {
      pattern:'Practice Raven-style matrices daily — spot count/rotation/size rules first.',
      spatial:'Play mental-rotation puzzles and paper-fold games to strengthen visualization.',
      logic  :'Try seating & syllogism puzzles — force yourself to draw the constraints on paper.',
      memory :'Do digit-span or N-back drills. Even 3 minutes a day rewires working memory.',
      speed  :'Push yourself to answer faster on the easy ones — leave time budget for the hard.'
    };
    if(weakest)     tips.push('🎯 Train more · '+cap1(weakest[0])+': '+advice[weakest[0]]);
    if(secondWeak && secondWeak[0] !== weakest[0]) tips.push('💡 Also work on '+cap1(secondWeak[0])+' — '+advice[secondWeak[0]].split(' — ')[0]);
    if(strongest)   tips.push('💪 Your strength · '+cap1(strongest[0])+' is above the rest. Lean on it in future tests.');
    return tips.slice(0,3);
  }
