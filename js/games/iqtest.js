/* Color palette read from CSS variables at first use, with sensible fallbacks
 * so nothing looks broken if a variable is missing. We also honor a colorblind-
 * safe toggle stored in localStorage (nz_iq_cbsafe). */
function IQ_palette(){
  try{
    const cs=getComputedStyle(document.documentElement);
    const cb=!!S('nz_iq_cbsafe');
    return {
      ink   : (cs.getPropertyValue('--text')  ||'#0F172A').trim(),
      muted : (cs.getPropertyValue('--text2') ||'#64748B').trim(),
      line  : (cs.getPropertyValue('--border')||'#E5E7EB').trim(),
      surf  : (cs.getPropertyValue('--card')  ||'#FFFFFF').trim(),
      prim  : (cs.getPropertyValue('--primary')||'#7C3AED').trim(),
      accent: '#4F8EF7',
      good  : cb ? '#2563EB' : '#22C55E',
      bad   : cb ? '#EA580C' : '#EF4444',
      warn  : '#F59E0B',
      cb    : cb
    };
  }catch(e){
    return { ink:'#0F172A', muted:'#64748B', line:'#E5E7EB', surf:'#FFFFFF',
             prim:'#7C3AED', accent:'#4F8EF7', good:'#22C55E', bad:'#EF4444',
             warn:'#F59E0B', cb:false };
  }
}

/* Build one primitive shape centered at (cx,cy) inside a bbox of size `sz`.
 * `spec` is a small object: { kind, fill?, stroke?, rot?, count?, size? }.
 * Kinds: circle, square, triangle, diamond, star, cross, arrow, dot, ring,
 *        hex, halfcircle, tri-down. */
function IQ_shape(spec, cx, cy, sz){
  const p=IQ_palette();
  const stroke = spec.stroke || p.ink;
  const fill   = spec.fill   || 'none';
  const sw     = spec.sw != null ? spec.sw : 2;
  const rot    = spec.rot || 0;
  const s      = (spec.size!=null ? spec.size : 1) * sz * 0.42;
  const g = `<g transform="translate(${cx} ${cy}) rotate(${rot})">`;
  const attrs = `fill="${fill}" stroke="${stroke}" stroke-width="${sw}" stroke-linejoin="round" stroke-linecap="round"`;
  let body='';
  switch(spec.kind){
    case 'circle':      body=`<circle cx="0" cy="0" r="${s}" ${attrs}/>`; break;
    case 'ring':        body=`<circle cx="0" cy="0" r="${s}" fill="none" stroke="${stroke}" stroke-width="${sw}"/>`; break;
    case 'dot':         body=`<circle cx="0" cy="0" r="${s*0.35}" fill="${stroke}" stroke="none"/>`; break;
    case 'square':      body=`<rect x="${-s}" y="${-s}" width="${s*2}" height="${s*2}" ${attrs}/>`; break;
    case 'diamond':     body=`<polygon points="0,${-s} ${s},0 0,${s} ${-s},0" ${attrs}/>`; break;
    case 'triangle':    body=`<polygon points="0,${-s} ${s*0.92},${s*0.72} ${-s*0.92},${s*0.72}" ${attrs}/>`; break;
    case 'tri-down':    body=`<polygon points="0,${s} ${s*0.92},${-s*0.72} ${-s*0.92},${-s*0.72}" ${attrs}/>`; break;
    case 'hex': {
      const pts=[];for(let i=0;i<6;i++){const a=(Math.PI/3)*i-Math.PI/2;pts.push(`${(Math.cos(a)*s).toFixed(2)},${(Math.sin(a)*s).toFixed(2)}`);}
      body=`<polygon points="${pts.join(' ')}" ${attrs}/>`; break;
    }
    case 'star': {
      const pts=[];for(let i=0;i<10;i++){const a=(Math.PI/5)*i-Math.PI/2;const r=(i%2)?s*0.45:s;pts.push(`${(Math.cos(a)*r).toFixed(2)},${(Math.sin(a)*r).toFixed(2)}`);}
      body=`<polygon points="${pts.join(' ')}" ${attrs}/>`; break;
    }
    case 'cross':       body=`<path d="M ${-s} 0 L ${s} 0 M 0 ${-s} L 0 ${s}" fill="none" stroke="${stroke}" stroke-width="${sw*1.4}" stroke-linecap="round"/>`; break;
    case 'arrow':       body=`<path d="M ${-s} 0 L ${s*0.7} 0 M ${s*0.7} 0 L ${s*0.2} ${-s*0.5} M ${s*0.7} 0 L ${s*0.2} ${s*0.5}" fill="none" stroke="${stroke}" stroke-width="${sw*1.4}" stroke-linecap="round" stroke-linejoin="round"/>`; break;
    case 'halfcircle':  body=`<path d="M ${-s} 0 A ${s} ${s} 0 0 1 ${s} 0 Z" ${attrs}/>`; break;
    case 'plus':        body=`<path d="M ${-s*0.35} ${-s} h ${s*0.7} v ${s*0.65} h ${s*0.65} v ${s*0.7} h ${-s*0.65} v ${s*0.65} h ${-s*0.7} v ${-s*0.65} h ${-s*0.65} v ${-s*0.7} h ${s*0.65} Z" ${attrs}/>`; break;
    case 'l-shape':     body=`<path d="M ${-s} ${-s} h ${s*2} v ${s*0.75} h ${-s*1.25} v ${s*1.25} h ${-s*0.75} Z" ${attrs}/>`; break;
    default:            body='';
  }
  return g + body + '</g>';
}

/* Draw N shapes evenly in a cell — used for count-progression matrices. */
function IQ_shapesInCell(spec, count, cx, cy, sz){
  if(count<=0) return '';
  const R = sz*0.28;
  let out='';
  if(count===1){
    out += IQ_shape({...spec, size:0.9}, cx, cy, sz);
  }else{
    for(let i=0;i<count;i++){
      const a=(Math.PI*2/count)*i - Math.PI/2;
      const x=cx+Math.cos(a)*R;
      const y=cy+Math.sin(a)*R;
      out += IQ_shape({...spec, size:0.55}, x, y, sz);
    }
  }
  return out;
}

/* One matrix cell painter. `cellSpec` is one of:
 *   { blank:true }                                   → the "?" cell
 *   { kind, rot?, count?, fill?, stroke?, size? }    → single shape
 *   { multi:[cellSpec, ...] }                        → overlay multiple shapes
 *   { count, kind, fill?, stroke? }                  → draw `count` copies
 */
function IQ_matrixCell(cellSpec, cx, cy, sz, opts){
  const p=IQ_palette();
  const isBlank=!!(cellSpec && cellSpec.blank);
  const border=`<rect x="${cx-sz/2}" y="${cy-sz/2}" width="${sz}" height="${sz}" rx="8" ry="8" fill="${(opts&&opts.bg)||'transparent'}" stroke="${(opts&&opts.borderColor)||p.line}" stroke-width="1.5"/>`;
  let content='';
  if(isBlank){
    content = `<text x="${cx}" y="${cy+sz*0.14}" text-anchor="middle" font-size="${sz*0.42}" font-weight="800" fill="${p.muted}" font-family="system-ui,-apple-system,sans-serif">?</text>`;
  }else if(cellSpec && cellSpec.multi){
    for(const s of cellSpec.multi) content += IQ_shape(s, cx, cy, sz);
  }else if(cellSpec && cellSpec.count!=null){
    content = IQ_shapesInCell(cellSpec, cellSpec.count, cx, cy, sz);
  }else if(cellSpec){
    content = IQ_shape(cellSpec, cx, cy, sz);
  }
  return border + content;
}

/* Draw an R×C matrix from a flat array of cellSpecs (row-major). */
function IQ_drawMatrix(rows, cols, cells, opts){
  const w = 240, h = 240;
  const pad = 10;
  const cw = (w - pad*2)/cols, ch = (h - pad*2)/rows;
  const sz = Math.min(cw, ch) - 8;
  let svg = `<svg viewBox="0 0 ${w} ${h}" xmlns="http://www.w3.org/2000/svg" class="iq-svg iq-svg-matrix">`;
  for(let r=0;r<rows;r++){
    for(let c=0;c<cols;c++){
      const cx = pad + cw*c + cw/2;
      const cy = pad + ch*r + ch/2;
      const spec = cells[r*cols + c];
      svg += IQ_matrixCell(spec, cx, cy, sz, opts||{});
    }
  }
  svg += '</svg>';
  return svg;
}

/* Small "option tile" — a bordered box drawing exactly one cellSpec. Used for
 * A/B/C/D visual choices in matrix, rotation, sequence questions. */
function IQ_optionTile(cellSpec){
  const p=IQ_palette();
  const w=90,h=90,cx=w/2,cy=h/2,sz=w-16;
  let svg=`<svg viewBox="0 0 ${w} ${h}" xmlns="http://www.w3.org/2000/svg" class="iq-svg iq-svg-opt">`;
  svg += IQ_matrixCell(cellSpec, cx, cy, sz, {borderColor:'transparent'});
  svg += '</svg>';
  return svg;
}

/* Simple horizontal sequence: N frames left→right with an arrow, last is "?". */
function IQ_drawSequence(cells){
  const p=IQ_palette();
  const n=cells.length;
  const cw=70, gap=8;
  const w = n*cw + (n-1)*gap + 20;
  const h = 90;
  let svg=`<svg viewBox="0 0 ${w} ${h}" xmlns="http://www.w3.org/2000/svg" class="iq-svg iq-svg-seq">`;
  for(let i=0;i<n;i++){
    const cx = 10 + i*(cw+gap) + cw/2;
    const cy = h/2;
    svg += IQ_matrixCell(cells[i], cx, cy, cw-8, {});
    if(i<n-1){
      const ax = 10 + (i+1)*cw + i*gap - 2;
      svg += `<path d="M ${ax} ${cy} l ${gap+4} 0" stroke="${p.muted}" stroke-width="1.5" stroke-linecap="round"/>`;
    }
  }
  svg += '</svg>';
  return svg;
}

/* Cube-net drawing: a cross-shape unfolded cube with 6 labeled faces. */
function IQ_drawCubeNet(faceLabels, faceColors){
  const p=IQ_palette();
  const s=42;
  const w=s*4+20, h=s*3+20;
  const ox=10, oy=10;
  /* Positions in a cross: [col,row] for faces top, left, front, right, back, bottom */
  const pos=[ [1,0], [0,1], [1,1], [2,1], [3,1], [1,2] ];
  let svg=`<svg viewBox="0 0 ${w} ${h}" xmlns="http://www.w3.org/2000/svg" class="iq-svg iq-svg-cube">`;
  for(let i=0;i<6;i++){
    const [c,r]=pos[i];
    const x=ox+c*s, y=oy+r*s;
    const fill=(faceColors&&faceColors[i])||p.surf;
    svg += `<rect x="${x}" y="${y}" width="${s}" height="${s}" rx="4" ry="4" fill="${fill}" stroke="${p.ink}" stroke-width="1.5"/>`;
    if(faceLabels&&faceLabels[i]){
      svg += `<text x="${x+s/2}" y="${y+s/2+5}" text-anchor="middle" font-size="16" font-weight="800" fill="${p.ink}" font-family="system-ui,sans-serif">${faceLabels[i]}</text>`;
    }
  }
  svg += '</svg>';
  return svg;
}

